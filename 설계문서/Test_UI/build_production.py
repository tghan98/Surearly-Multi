"""Generate the production UI from the development UI."""

import argparse
from pathlib import Path
import re
import sys


HERE = Path(__file__).resolve().parent
SOURCE = HERE / "multi.html"
OUTPUT = HERE / "multi-production.html"

BLOCKS = {
    "reset-style": "css",
    "qc-style": "css",
    "reset-button": "html",
    "qc-button": "html",
    "reset-notice": "html",
    "qc-notice": "html",
    "reset-ref": "js",
    "qc-ref": "js",
    "reset-status": "js",
    "qc-status": "js",
    "reset-handler": "js",
    "qc-handler": "js",
}


def marker(name: str, kind: str, edge: str) -> str:
    label = f"DEV-ONLY:{name} {edge}"
    if kind == "css":
        return f"/* {label} */"
    if kind == "html":
        return f"<!-- {label} -->"
    return f"// {label}"


def generate(source: str) -> str:
    lines = source.splitlines(keepends=True)
    markers = {}
    for name, kind in BLOCKS.items():
        for edge in ("START", "END"):
            token = marker(name, kind, edge)
            if sum(line.strip() == token for line in lines) != 1:
                raise ValueError(f"Expected exactly one {token}")
            markers[token] = (name, edge)

    output = []
    active = None
    for line in lines:
        token = line.strip()
        if token in markers:
            name, edge = markers[token]
            if edge == "START":
                if active is not None:
                    raise ValueError(f"Nested DEV-ONLY block: {name}")
                active = name
            elif active != name:
                raise ValueError(f"Unmatched DEV-ONLY block: {name}")
            else:
                active = None
        elif active is None:
            output.append(line)
    if active is not None:
        raise ValueError(f"Unclosed DEV-ONLY block: {active}")

    production = "<!-- Generated by build_production.py from multi.html. Do not edit. -->\n" + "".join(output)
    forbidden = (
        r"DEV-ONLY:",
        r"\bbtnQcReset\b",
        r"\bbtnReset\b",
        r"\bQC_ARM_TIMEOUT_MS\b",
        r"['\"][QR]['\"]",
    )
    for pattern in forbidden:
        if re.search(pattern, production):
            raise ValueError(f"Production UI still contains {pattern}")
    for required in ("sendInput", "hexMode", "lineEnding", "btnSend", "btnRawDump", "btnSaveCsv", "btnExportPdf"):
        if required not in production:
            raise ValueError(f"Production UI lost {required}")
    return production


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated file is outdated")
    args = parser.parse_args()

    try:
        production = generate(SOURCE.read_text(encoding="utf-8"))
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != production:
                raise ValueError(f"{OUTPUT.name} is missing or outdated")
        else:
            OUTPUT.write_text(production, encoding="utf-8", newline="\n")
    except (OSError, ValueError) as exc:
        print(exc, file=sys.stderr)
        return 1
    print(f"{OUTPUT.name}: {'current' if args.check else 'generated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
